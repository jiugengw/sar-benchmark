"""Export every packaged ZIP's training history for the interactive curve comparison page.

Reads each `<zip stem>.run.json` (see docs/RUN_TEMPLATE.md) with the loaders in plot_training_curves.py and writes
reports/curve-compare/data.js, which reports/curve-compare/index.html loads (it works opened straight from disk).

    python tools/build_curve_compare.py
"""
import json
import re
from pathlib import Path

from plot_training_curves import ROOT, load, resolve

OUT = ROOT / 'reports/curve-compare/data.js'
DETECTOR_TYPES = {'ultralytics', 'terramind'}


def official_scores():
    """ZIP stem -> official Δm, from the submissions index."""
    scores = {}
    for line in (ROOT / 'submissions/README.md').read_text().splitlines():
        match = re.match(r'\|\s*\d+\s*\|[^|]*\|\s*\[([^\]]+)\.zip\][^|]*\|[^|]*\|\s*([+−-]?\d+\.\d+)\s*\|', line)
        if match:
            scores[match.group(1)] = float(match.group(2).replace('−', '-'))
    return scores


def rounded(values, digits=4):
    return [None if v is None else round(v, digits) for v in values]


def stage(source):
    history = load(source)
    metrics = {}
    for name, values in history['metrics'].items():
        key = 'macro-F1' if name.startswith('macro-F1') else name
        if key not in metrics:  # quick-head files carry full and clean F1; keep the full-holdout one
            metrics[key] = rounded(values)
    losses = {name: [rounded(train), rounded(val)] for name, (train, val) in history['losses'].items()}
    return {'label': source.get('label', source['type']), 'type': source['type'],
            'epochs': history['epochs'], 'lossEpochs': history.get('loss_epochs') or history['epochs'],
            'metrics': metrics, 'losses': losses, 'note': history.get('note', '')}


def main():
    official = official_scores()
    runs = []
    for zip_path in sorted(p for folder in ('submissions', 'nonsubmissions') for p in (ROOT / folder).rglob('*.zip')):
        run_path = zip_path.with_name(zip_path.stem + '.run.json')
        if not run_path.is_file():
            continue
        run = resolve(run_path)
        if not run['histories']:
            continue
        stages = [stage(source) for source in run['histories']]
        types = {s['type'] for s in stages}
        family = ('YOLO / RT-DETR' if 'ultralytics' in types else
                  'ViT / TerraMind / ResNet' if 'terramind' in types else 'other')
        submitted = zip_path.relative_to(ROOT).parts[0] == 'submissions'
        runs.append({'id': str(zip_path.relative_to(ROOT)), 'name': zip_path.stem, 'submitted': submitted,
                     'official': official.get(zip_path.stem), 'family': family, 'note': run.get('note', ''),
                     'stages': stages})
    runs.sort(key=lambda r: (not r['submitted'], -(r['official'] if r['official'] is not None else -99), r['name']))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('// Generated by tools/build_curve_compare.py; do not edit.\nwindow.CURVE_RUNS = '
                   + json.dumps(runs, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'{len(runs)} runs with curves -> {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.2f} MB)')


if __name__ == '__main__':
    main()
